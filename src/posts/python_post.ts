const PYODIDE_URL = 'https://cdn.jsdelivr.net/pyodide/v0.26.4/full/pyodide.js';
let pyodidePromise: Promise<any> | null = null;

async function loadPyodide(): Promise<any> {
  if (pyodidePromise) return pyodidePromise;
  pyodidePromise = (async () => {
    if (!(window as any).loadPyodide) {
      await new Promise<void>((resolve, reject) => { const s = document.createElement('script'); s.src = PYODIDE_URL; s.onload = () => resolve(); s.onerror = () => reject(new Error('Failed to load Pyodide')); document.head.appendChild(s); });
    }
    const py = await (window as any).loadPyodide({ indexURL: PYODIDE_URL.replace(/pyodide\.js$/, '') });
    py.FS.mkdirTree('/studio/robodk');
    // The official Apache-2.0 robodk.robomath / robofileio plus headless robodialogs, so unmodified RoboDK posts import cleanly
    py.FS.writeFile('/studio/robodk/__init__.py', 'from . import robomath, robodialogs, robofileio\nfrom .robomath import *\nfrom .robodialogs import *\nfrom .robofileio import *\n');
    py.FS.writeFile('/studio/robodk/robomath.py', robomathSrc);
    py.FS.writeFile('/studio/robodk/robodialogs.py', robodialogsSrc);
    py.FS.writeFile('/studio/robodk/robofileio.py', robofileioSrc);
    py.FS.writeFile('/studio/robodk/robolink.py', ROBOLINK_STUB);
    // legacy top-level modules used by older posts: `from robolink import *`, `from robodk import *`
    py.FS.writeFile('/studio/robolink.py', 'from robodk.robolink import *\n');
    py.FS.writeFile('/studio/post_shim.py', shimSrc);
    await py.runPythonAsync('import sys\nsys.path.insert(0, "/studio")\nimport post_shim');
    return py;
  })();
  return pyodidePromise;
}

/** Serialize PostEvents for the Python side (poses as column-major 16 arrays). */
export function eventsToJSON(p: PostProgram): string {
  return JSON.stringify(p.events.map((e) => { const o: any = { ...e }; for (const k of ['pose', 'via']) if (o[k] instanceof Float64Array) o[k] = Array.from(o[k]); return o; }));
}

/** Sources of every imported post file, written next to the running post so sibling imports (`from Fanuc_R30i import *`) resolve. */
const siblingSources = new Map<string, string>();
export function setSiblingPostSource(file: string, source: string): void { siblingSources.set(file.split(/[/\\]/).pop() ?? file, source); }

/**
 * Run a RoboDK Python post (source text) on a compiled program and its sub-programs: the post job goes through
 * post_shim.run_job_source (ProgStart ... ProgFinish, ProgSave into a virtual folder) and every file the post writes is
 * returned (multi-file posts: KUKA .src+.dat, VAL3 projects, zip archives as base64). The post log becomes post_log.txt.
 */
export async function runPythonPost(postSource: string, program: PostProgram, opts: { name?: string; options?: Record<string, any> } = {}): Promise<PostFile[]> {
  const py = await loadPyodide();
  py.FS.mkdirTree('/studio/posts');
  for (const [file, src] of siblingSources) py.FS.writeFile(`/studio/posts/${file}`, src);
  const job = toPostJob(program, { header_comments: [`Program generated by VerticalBot Studio for ${program.robotName}`, 'Using nominal kinematics.'], ...(opts.options?.maxLines ? { lines_x_prog: opts.options.maxLines } : {}) });
  py.globals.set('__post_src', postSource);
  py.globals.set('__job', JSON.stringify(job));
  py.globals.set('__post_name', (opts.name ?? 'robodk_post').replace(/\.py$/i, '').replace(/\W+/g, '_'));
  const result = await py.runPythonAsync(['import post_shim', 'post_shim.run_job_source(__post_src, __job, "/studio/out", __post_name)'].join('\n'));
  const r = JSON.parse(result);
  if (!r.ok) throw new Error(`Python post failed: ${r.error}`);
  const files: PostFile[] = (r.files ?? []).map((f: any) => ({ name: f.name, content: f.content, ...(f.encoding === 'base64' ? { encoding: 'base64' as const } : {}) }));
  if (r.log) files.push({ name: 'post_log.txt', content: String(r.log) });
  return files;
}

/** Register a user-provided Python post as a selectable post processor (async generation via `generateAsync`). */
export function registerPythonPost(id: string, name: string, source: string): PostProcessor & { generateAsync: (p: PostProgram, options?: Record<string, any>) => Promise<PostFile[]> } {
  const post = {
    id, name: `${name} (Python post)`, brand: 'Custom', extension: 'txt',
    generate: (_p: PostProgram): PostFile[] => [{ name: 'README.txt', content: 'This is a Python post processor: use generateAsync / the Export dialog (runs in Pyodide).' }],
    generateAsync: (p: PostProgram, options?: Record<string, any>) => runPythonPost(source, p, { name, options }),
  };
  registerPost(post);
  return post;
}
