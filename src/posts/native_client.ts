/**
 * Client side of the native RoboDK posts (server/posts_native.ts): RoboDK's own post processors — including the
 * compiled libspp / vXY ones that cannot run in the browser — executed by the studio server with RoboDK's embedded
 * Python. `registerNativePosts(server)` lists the server's RoboDK posts and registers each one as an asynchronous post
 * (`RDK_<name>`); `nativePost(name)` builds one for a robot whose RoboDK post has no built-in equivalent (the RoboDK
 * post name then resolves to it: getPost('ABB_RAPID_IRC5_Robtargets') -> RDK_ABB_RAPID_IRC5_Robtargets).
 *
 * In the browser the posts run through HTTP (POST /posts/native/run). Inside the server process (headless station of
 * the RoboDK API: MakeProgram from Python / the official robodk package) `setLocalNativePosts` plugs the local runner
 * in, so the same posts work without HTTP.
 */
import { PostFile, PostProcessor, PostProgram, registerPost, getPost } from './base';
import { toPostJob } from './job';

let serverBase = '';
/** Studio server base URL (http://host:port; a ws:// URL is converted). Empty: native posts unavailable. */
export function setNativePostServer(url: string): void { serverBase = url.replace(/^ws(s?):/, 'http$1:').replace(/\/+$/, ''); }
export function nativePostServer(): string { return serverBase; }

/** Result of one native post run (server/posts_native.ts NativePostResult). */
export interface NativeRunResult { ok: boolean; files?: Array<{ name: string; content: string; encoding?: string }>; log?: string; error?: string }
/** In-process access to the native posts (server side): list the post names and run one on a post job. */
export interface LocalNativePosts { list(): string[]; run(post: string, job: unknown, source?: string): Promise<NativeRunResult> }
let local: LocalNativePosts | null = null;
export function setLocalNativePosts(l: LocalNativePosts | null): void { local = l; }

function toFiles(r: NativeRunResult | null | undefined): PostFile[] {
  if (!r?.ok) throw new Error(`RoboDK post failed: ${r?.error ?? 'no answer from the studio server'}`);
  const files: PostFile[] = (r.files ?? []).map((f) => ({ name: f.name, content: f.content, ...(f.encoding === 'base64' ? { encoding: 'base64' as const } : {}) }));
  if (r.log) files.push({ name: 'post_log.txt', content: String(r.log) });
  return files;
}

/** Run a RoboDK post (name from the server's Posts folder, or a user post source) on a compiled program. */
export async function runNativePost(post: string, program: PostProgram, opts: { source?: string; options?: Record<string, any> } = {}): Promise<PostFile[]> {
  if (!serverBase && !local) throw new Error('Native RoboDK posts need the studio server (npm run server, open the studio with ?server=...)');
  const job = toPostJob(program, { header_comments: [`Program generated by VerticalBot Studio for ${program.robotName} on ${new Date().toLocaleString()}`, 'Using nominal kinematics.'], ...(opts.options?.maxLines ? { lines_x_prog: opts.options.maxLines } : {}) });
  if (local) return toFiles(await local.run(post, job, opts.source));
  const r = await fetch(`${serverBase}/posts/native/run`, { method: 'POST', headers: { 'content-type': 'application/json' }, body: JSON.stringify({ post, job, source: opts.source }) });
  return toFiles(await r.json());
}

export function nativePost(name: string, opts: { source?: string; label?: string } = {}): PostProcessor {
  return {
    id: `RDK_${name.replace(/\W+/g, '_')}`, name: `${opts.label ?? name} (RoboDK post, server)`, brand: 'RoboDK', extension: 'txt',
    description: `RoboDK's own ${name} post processor executed by the studio server with RoboDK's Python.`,
    // the RoboDK post name resolves to this post only when the studio has no built-in equivalent
    aliases: getPost(name) ? [] : [name],
    generate: () => [{ name: 'README.txt', content: `RoboDK post "${name}" runs on the studio server: use the Export dialog (asynchronous generation).` }],
    generateAsync: (p: PostProgram, options?: Record<string, any>) => runNativePost(name, p, { source: opts.source, options }),
  };
}

/** Register every RoboDK post the server can run. Returns the registered ids ([] when no server / no RoboDK). */
export async function registerNativePosts(server = serverBase): Promise<string[]> {
  if (local) return local.list().map((n) => { const p = nativePost(n); registerPost(p); return p.id; });
  if (server) setNativePostServer(server);
  if (!serverBase) return [];
  try {
    const r = await (await fetch(`${serverBase}/posts/native`)).json();
    if (!r?.available) return [];
    return (r.posts as string[]).map((n) => { const p = nativePost(n); registerPost(p); return p.id; });
  } catch { return []; }
}
