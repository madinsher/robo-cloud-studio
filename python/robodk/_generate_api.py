"""Generate python/robodk/_official.py from RoboDK's official robolink.py (Apache-2.0, RoboDK Inc.).

    py -3 python/robodk/_generate_api.py [C:/RoboDK/Python/robodk/robolink.py]

The generated module holds everything the drop-in must mirror *exactly*:
  - every module-level constant with its official value (ITEM_TYPE_*, ROBOTCOM_*, MAKE_ROBOT_*, SPRAY_*, PATH_*, ...),
  - the InstructionListJointsFlags / PathErrorFlags enums and ConvertErrorCodeToJointErrorType,
  - the exception classes (TargetReachError, StoppedError, InputError, LicenseError),
  - the helpers RoboDKInstallFound, getPathRoboDK, getPathIcon, import_install, EmbedWindow,
  - RobolinkAPI / ItemAPI: one JSON-RPC wrapper per public official method, with the official signature and defaults.
python/robodk/robolink.py subclasses RobolinkAPI / ItemAPI and overrides the methods whose return value needs a
Python-side conversion (robomath.Mat, tuples, files). Re-run this script when RoboDK updates its API.
Needs Python >= 3.9 (ast.unparse); the generated file runs on Python >= 3.6.
"""
import ast
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else 'C:/RoboDK/Python/robodk/robolink.py'
OUT = os.path.join(HERE, '_official.py')
HELPERS = ('RoboDKInstallFound', 'getPathRoboDK', 'getPathIcon', 'import_install', 'EmbedWindow')


def strip_annotations(fn):
    a = fn.args
    for x in a.posonlyargs + a.args + a.kwonlyargs:
        x.annotation = None
    if a.vararg:
        a.vararg.annotation = None
    if a.kwarg:
        a.kwarg.annotation = None
    fn.returns = None
    for node in ast.walk(fn):
        if isinstance(node, ast.AnnAssign) and node.value is not None:
            pass
    return fn


def doc_first_line(fn):
    d = ast.get_docstring(fn) or ''
    line = d.strip().splitlines()[0].strip() if d.strip() else ''
    return line.replace('\\', '\\\\').replace('"""', "'''")


def wrapper(cls, fn, rpc):
    fn = strip_annotations(fn)
    a = fn.args
    names = [x.arg for x in a.posonlyargs + a.args][1:]
    sig = ast.unparse(a)
    call = '[' + ', '.join(names) + ']'
    if a.vararg:
        call += ' + list(%s)' % a.vararg.arg
    doc = doc_first_line(fn)
    lines = ['    def %s(%s):' % (fn.name, sig)]
    if doc:
        lines.append('        """%s"""' % doc)
    lines.append('        return self.%s(%r, %s)' % (rpc, fn.name, call))
    return '\n'.join(lines)


def main():
    src = open(SRC, encoding='utf-8').read()
    tree = ast.parse(src)
    out = ['# -*- coding: utf-8 -*-',
           '# GENERATED by python/robodk/_generate_api.py from %s -- do not edit by hand.' % SRC.replace('\\', '/'),
           '# Constants, exceptions, helpers and method signatures: RoboDK API (Apache License 2.0, RoboDK Inc.).',
           '# The studio drop-in (robolink.py) subclasses RobolinkAPI / ItemAPI; every wrapper sends a JSON-RPC call.',
           'import sys', 'import os', 'import time', 'import threading', 'import struct',
           'from . import robomath', '']
    consts, enums, excs, helpers, rob, itm = [], [], [], [], [], []
    rob_names, itm_names, const_names = [], [], []
    for n in tree.body:
        if isinstance(n, ast.Assign) and all(isinstance(t, ast.Name) for t in n.targets):
            consts.append(ast.unparse(n))
            const_names += [t.id for t in n.targets]
        elif isinstance(n, ast.AnnAssign) and isinstance(n.target, ast.Name) and n.value is not None:
            consts.append('%s = %s' % (n.target.id, ast.unparse(n.value)))
            const_names.append(n.target.id)
        elif isinstance(n, ast.If) and 'IntFlag' in ast.unparse(n.body[0]) if isinstance(n, ast.If) and n.body else False:
            enums.append(ast.unparse(n))
        elif isinstance(n, ast.ClassDef) and any(ast.unparse(b) == 'Exception' for b in n.bases):
            excs.append(ast.unparse(n))
        elif isinstance(n, ast.FunctionDef) and n.name in HELPERS:
            helpers.append(ast.unparse(strip_annotations(n)))
        elif isinstance(n, ast.ClassDef) and n.name in ('Robolink', 'Item'):
            for m in n.body:
                if isinstance(m, ast.FunctionDef) and not m.name.startswith('_'):
                    if n.name == 'Robolink':
                        rob.append(wrapper('Robolink', m, '_rpc'))
                        rob_names.append(m.name)
                    else:
                        itm.append(wrapper('Item', m, '_rpc_item'))
                        itm_names.append(m.name)
    out.append('# ---- constants (official values) ----')
    out += consts
    out.append('')
    out.append('# ---- enums ----')
    out += enums
    out.append('')
    out.append('# ---- exceptions ----')
    out += excs
    out.append('')
    out.append('# ---- helpers ----')
    out += helpers
    out.append('')
    out.append('OFFICIAL_CONSTANTS = (%s)' % ', '.join(repr(c) for c in const_names))
    out.append('OFFICIAL_ROBOLINK_METHODS = (%s)' % ', '.join(repr(c) for c in rob_names))
    out.append('OFFICIAL_ITEM_METHODS = (%s)' % ', '.join(repr(c) for c in itm_names))
    out.append('')
    out.append('')
    out.append('class RobolinkAPI(object):')
    out.append('    """Official Robolink surface; each method is a JSON-RPC call (self._rpc(name, params))."""')
    out.append('')
    out += [w + '\n' for w in rob]
    out.append('')
    out.append('class ItemAPI(object):')
    out.append('    """Official Item surface; each method is a JSON-RPC call on this item (self._rpc_item(name, params))."""')
    out.append('')
    out += [w + '\n' for w in itm]
    text = '\n'.join(out) + '\n'
    compile(text, OUT, 'exec')
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)
    print('wrote %s: %d constants, %d Robolink methods, %d Item methods, %d exceptions' % (OUT, len(const_names), len(rob_names), len(itm_names), len(excs)))


if __name__ == '__main__':
    main()
