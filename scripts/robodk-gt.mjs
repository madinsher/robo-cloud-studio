#!/usr/bin/env node
/**
 * RoboDK Library compatibility report.
 *
 *   node scripts/robodk-gt.mjs [--sim] [--only <substring>] [--jobs 3] [--timeout 900] [--out docs/robodk-library-compat.md]
 *
 * Runs tests/robodk_gt.test.ts once per ground-truth fixture (tests/fixtures/robodk_gt/*.json.gz) in its own vitest
 * process with a timeout, collects the per-file JSON results and writes the markdown report: import issues, FK error,
 * program validity, joint deviation and cycle-time ratio against RoboDK 5.9.4.
 */
import { spawn } from 'node:child_process';
import { readdirSync, readFileSync, writeFileSync, mkdirSync, existsSync, rmSync } from 'node:fs';
import { join } from 'node:path';
import { tmpdir } from 'node:os';

const args = process.argv.slice(2);
const opt = (name, def) => { const i = args.indexOf(`--${name}`); return i >= 0 ? args[i + 1] : def; };
const SIM = args.includes('--sim');
const ONLY = opt('only', '');
const JOBS = Number(opt('jobs', '3'));
const TIMEOUT = Number(opt('timeout', SIM ? '3600' : '900')) * 1000;
const OUTMD = opt('out', 'docs/robodk-library-compat.md');
const GT = 'tests/fixtures/robodk_gt';
const RES = join(tmpdir(), `robodk-gt-${process.pid}`);
mkdirSync(RES, { recursive: true });

const fixtures = readdirSync(GT).filter((f) => f.endsWith('.json.gz') && (!ONLY || f.includes(ONLY))).sort();
const vitest = join('node_modules', 'vitest', 'vitest.mjs');
const status = new Map();

function runOne(f) {
  return new Promise((resolve) => {
    const t0 = Date.now();
    const env = { ...process.env, ROBODK_GT_ONLY: f, ROBODK_GT_OUT: RES, ...(SIM ? { ROBODK_GT_SIM: '1' } : {}) };
    const child = spawn(process.execPath, [vitest, 'run', 'tests/robodk_gt.test.ts', '--reporter=dot'], { env, stdio: ['ignore', 'pipe', 'pipe'] });
    let log = '';
    child.stdout.on('data', (d) => { log += d; });
    child.stderr.on('data', (d) => { log += d; });
    const timer = setTimeout(() => { status.set(f, { state: 'timeout', ms: Date.now() - t0 }); child.kill('SIGKILL'); }, TIMEOUT);
    child.on('close', (code) => {
      clearTimeout(timer);
      if (!status.has(f)) status.set(f, { state: /skipped/.test(log) && !/passed|failed/.test(log.replace(/\d+ skipped/, '')) ? 'skipped' : code === 0 ? 'pass' : 'fail', ms: Date.now() - t0, log: code ? log.slice(-1500) : '' });
      process.stdout.write(`${status.get(f).state.padEnd(7)} ${((Date.now() - t0) / 1000).toFixed(1).padStart(6)} s  ${f}\n`);
      resolve();
    });
  });
}

const queue = [...fixtures];
await Promise.all(Array.from({ length: Math.max(1, JOBS) }, async () => { while (queue.length) await runOne(queue.shift()); }));

const rows = fixtures.map((f) => {
  const p = join(RES, f.replace(/\.json\.gz$/, '') + '.json');
  const r = existsSync(p) ? JSON.parse(readFileSync(p, 'utf8')) : null;
  return { f, s: status.get(f) ?? { state: 'missing' }, r };
});
rmSync(RES, { recursive: true, force: true });

const name = (f) => f.replace(/_\.json\.gz$/, '');
const fkMax = (r) => { const v = Object.values(r?.fk ?? {}); return v.length ? Math.max(...v) : null; };
const pass = rows.filter((x) => x.s.state === 'pass').length;
const fkAll = rows.map((x) => fkMax(x.r)).filter((v) => v !== null);
const fkWorst = fkAll.length ? Math.max(...fkAll) : 0;
const robots = rows.reduce((n, x) => n + Object.keys(x.r?.fk ?? {}).length, 0);
const lines = [];
lines.push('# RoboDK Library compatibility (import vs RoboDK 5.9.4 ground truth)');
lines.push('');
lines.push(`Generated by \`node scripts/robodk-gt.mjs${SIM ? ' --sim' : ''}\` on ${new Date().toISOString().slice(0, 10)} from \`tests/robodk_gt.test.ts\` and the ground truth in \`tests/fixtures/robodk_gt\` (one RoboDK dump per Library file).`);
lines.push('');
lines.push(`* Files: **${fixtures.length}**, import-level checks passing: **${pass}**, failing: ${rows.filter((x) => x.s.state === 'fail').length}, timeouts: ${rows.filter((x) => x.s.state === 'timeout').length}, skipped (no C:/RoboDK/Library): ${rows.filter((x) => x.s.state === 'skipped').length}.`);
lines.push(`* Robot FK compared at 12 random joint vectors per robot (synchronised external axes included): **${robots} robots, worst error ${fkWorst.toFixed(4)}** (mm + mrad; tolerance 0.01).`);
lines.push('* Checked per file: item tree (type, name, parent), absolute poses, robot DOF / limits / current + home joints / FK / active tool + frame, tool TCPs, targets (pose, joints, joint flag, robot link), programs (robot link, instruction count, label, type, move type, target joints and pose), Python programs (name + source), machining links.');
if (SIM) lines.push('* Simulation: `ProgramSimulator.compile` per program vs `Item.Update()` (validity, cycle time) and `InstructionListJoints` (joints at the end of each move).');
else lines.push('* Simulation columns are empty in import-only mode; run with `--sim` (sets ROBODK_GT_SIM=1).');
lines.push('');
lines.push('| File | Result | Import s | FK max (mm+mrad) | Programs (RoboDK valid / ours ok) | Worst joint dev (°) | Cycle-time ratio (min–max) | Issues |');
lines.push('|---|---|---:|---:|---|---:|---|---|');
for (const { f, s, r } of rows) {
  const progs = r?.programs ?? [];
  const gtValid = progs.filter((p) => (p.gtValid ?? 0) >= 0.999).length;
  const ourOk = progs.filter((p) => p.ok).length;
  const dev = progs.map((p) => p.worstJointDeg).filter((v) => typeof v === 'number' && v >= 0);
  const ratio = progs.map((p) => p.timeRatio).filter((v) => typeof v === 'number');
  const fk = fkMax(r);
  const issues = r?.issues ?? (s.log ? [s.log.split('\n').filter(Boolean).slice(-3).join(' ')] : []);
  lines.push(`| ${name(f)} | ${s.state} | ${r ? (r.importMs / 1000).toFixed(1) : '-'} | ${fk === null ? '-' : fk.toFixed(4)} | ${progs.length ? `${gtValid} / ${SIM ? ourOk : '-'} of ${progs.length}` : '-'} | ${dev.length ? Math.max(...dev).toFixed(3) : '-'} | ${ratio.length ? `${Math.min(...ratio).toFixed(2)}–${Math.max(...ratio).toFixed(2)}` : '-'} | ${issues.length ? issues.length : ''} |`);
}
lines.push('');
lines.push('## Issues and approximations per file');
lines.push('');
for (const { f, s, r } of rows) {
  const issues = r?.issues ?? [];
  const dropped = r?.dropped ?? [];
  const notes = r?.notes ?? [];
  if (!issues.length && !dropped.length && !notes.length && s.state === 'pass') continue;
  lines.push(`### ${name(f)}`);
  if (s.state === 'timeout') lines.push(`* timed out after ${(TIMEOUT / 1000).toFixed(0)} s`);
  for (const i of issues) lines.push(`* ${i.replace(/\|/g, '\\|')}`);
  if (notes.length) lines.push(`* RoboDK-side differences (not import defects, ${notes.length}): ${notes.slice(0, 4).map((d) => d.replace(/\|/g, '\|')).join('; ')}${notes.length > 4 ? ' …' : ''}`);
  if (dropped.length) lines.push(`* importer report (${dropped.length} item(s) not imported or approximated): ${dropped.slice(0, 6).map((d) => d.replace(/\|/g, '\\|')).join('; ')}${dropped.length > 6 ? ' …' : ''}`);
  lines.push('');
}
writeFileSync(OUTMD, lines.join('\n') + '\n');
console.log(`\n${pass}/${fixtures.length} files pass; worst FK ${fkWorst.toFixed(4)}; report written to ${OUTMD}`);
process.exit(0);
