/**
 * The generator-level rules of RoboDK's MakeProgram that the studio reproduces (src/posts/base.ts compileForPost,
 * src/posts/robopost.ts, src/posts/rdk_job.ts), each from RoboDK 5.9.4's own intermediate post scripts of the Library
 * (tests/fixtures/posts_gt/library_loaded.tgz, dump_library_loaded.py):
 *  - the intermediate script (Post<program>.py) is parsed into RobotPost calls;
 *  - numbers reach the posts with 6 significant digits, poses as PosePP (KUKA xyzabc), pose noise below 1e-9 as 0;
 *  - a linear move to the point the robot is already at is skipped (same position and orientation, or same joints);
 *  - frame / tool ids are the number written as a word of its own, 0 for the robot's base frame;
 *  - a "Start thread" reaches the posts as code; program names lose blanks and non-ASCII characters.
 */
import { describe, it, expect } from 'vitest';
import { parseRdkJobScript, rdkJobToPostProgram, diffRdkCalls, recordPostCalls } from '../src/posts/rdk_job';
import { rdkPrecisionEvents, postProgName } from '../src/posts/robopost';
import { posePP, pose2Kuka } from '../src/posts/euler';
import { dropZeroLengthMoves, nameIndex, getPost, compileForPost, PostProgram, PostEvent } from '../src/posts/index';
import { createRobotFromLibrary } from '../src/core/items/library';
import { Station, Frame, Target } from '../src/core/items/item';
import { Program } from '../src/core/items/program';
import { identity, transl, multiply, rotz, roty, rotx, Mat4 } from '../src/core/math/pose';

const JOB = [
  '# RoboDK Python Intermediate file to generate robot programs.',
  "r = RobotPost(r\"\"\"KUKA_KRC2\"\"\",r\"\"\"KUKA KR 10 R900 sixx\"\"\",6, axes_type=['R','R','R','R','R','R'], native_name=r\"\"\"\"\"\", ip_com=r\"\"\"127.0.0.1\"\"\", api_port=20500)",
  '',
  'r.ProgStart(r"""GoHome""")',
  'r.RunMessage(r"""Program generated by RoboDK v5.9.4 for KUKA KR 10 R900 sixx on 26/10/2026 00:21:00""",True)',
  'r.setFrame(p(0,0,0,0,0,0),0,r"""KUKA KR 10 R900 sixx Base""")',
  'r.setTool(p(116.058,0,219.481,0,60,0),-1,r"""Spindle""")',
  'r.MoveJ(p(646.351,0,271.156,-180,8.2982,180),[0,-72.4995,126.226,0,-25.2288,-2.35289e-14],[0,0,1])',
  'r.MoveJ(None,[1,2,3,4,5,6],None)',
  'r.RunCode(r"""Pick 1""", True)',
  'r.RunCode(r"""MoveConveyor""")',
  'r.setSpeed(16.667)',
  'r.ProgFinish(r"""GoHome""")',
  'r.ProgSave(r"""C:/out/""",r"""GoHome""",False,False)',
].join('\n');

describe("RoboDK's intermediate post script", () => {
  it('parses the robot, the programs and every call with RoboDK literals (p(), None, lists, raw strings, flags)', () => {
    const j = parseRdkJobScript(JOB);
    expect(j.post).toBe('KUKA_KRC2');
    expect(j.robot).toBe('KUKA KR 10 R900 sixx');
    expect(j.dof).toBe(6);
    expect(j.programs.map((p) => p.name)).toEqual(['GoHome']);
    const c = j.programs[0].calls;
    expect(c.map((x) => x.fn)).toEqual(['RunMessage', 'setFrame', 'setTool', 'MoveJ', 'MoveJ', 'RunCode', 'RunCode', 'setSpeed']);
    expect(c[1].args).toEqual([{ pose: [0, 0, 0, 0, 0, 0] }, 0, 'KUKA KR 10 R900 sixx Base']);
    expect(c[3].args[1]).toEqual([0, -72.4995, 126.226, 0, -25.2288, -2.35289e-14]);
    expect(c[4].args).toEqual([null, [1, 2, 3, 4, 5, 6], null]);
    expect(c[6].args).toEqual(['MoveConveyor']);
    // PosePP(x,y,z,a,b,c) = transl * rotz(a) * roty(b) * rotx(c) (KUKA xyzabc)
    const m = posePP([646.351, 0, 271.156, -170, 8.2982, 160]);
    const ref = multiply(multiply(multiply(transl(646.351, 0, 271.156), rotz(-170 * Math.PI / 180)), roty(8.2982 * Math.PI / 180)), rotx(160 * Math.PI / 180));
    expect(Array.from(m).every((v, i) => Math.abs(v - ref[i]) < 1e-9)).toBe(true);
    // RoboDK's own calls as studio events: a joint target has pose None
    const p = rdkJobToPostProgram(j);
    expect(p.events.filter((e) => e.kind === 'moveJ').map((e: any) => e.jointTarget)).toEqual([false, true]);
  });

  it('compares the studio calls with RoboDK\'s: program names without blanks, RunCode / RunMessage flags default False', () => {
    const j = parseRdkJobScript(JOB);
    const mine = JSON.parse(JSON.stringify(j.programs));
    mine[0].calls[5].args[0] = 'Pick1';
    mine[0].calls[6].args = ['MoveConveyor', false];
    expect(diffRdkCalls(j.programs, mine)).toBeNull();
    mine[0].calls[3].args[1][1] = -72.6;
    expect(diffRdkCalls(j.programs, mine)).toMatch(/GoHome call 4: RoboDK MoveJ/);
  });
});

describe("the numbers RoboDK's posts receive", () => {
  it('6 significant digits for joints and PosePP poses; pose noise is 0 (RoboDK writes no pose value below 1e-6)', () => {
    const noisy = multiply(transl(123.4567891, -0.000000000000001, 10), rotz(1e-15));
    const ev: PostEvent[] = [{ kind: 'moveL', joints: [12.3456789, -0.000123456789, 100.000049, 0, 0, 0], pose: noisy, name: 'a' }];
    const [r] = rdkPrecisionEvents(ev) as any[];
    expect(r.joints).toEqual([12.3457, -0.000123457, 100, 0, 0, 0]);
    expect(pose2Kuka(r.pose)).toEqual([123.457, 0, 10, 0, 0, 0]);
  });

  it('program names as RoboDK hands them: blanks and non-ASCII characters removed (05.b "Sıde0" -> Sde0)', () => {
    expect(postProgName('Pick EarCup 1')).toBe('PickEarCup1');
    expect(postProgName('Sıde0')).toBe('Sde0');
  });

  it('frame / tool ids: a number written as a word of its own, -1 for "Gripper1" (06.f), 0 for the robot base frame (01.c)', () => {
    expect(nameIndex('Frame 2')).toBe(2);
    expect(nameIndex('Gripper1')).toBe(-1);
    expect(nameIndex('Section1')).toBe(-1);
    expect(nameIndex('Machining Reference 4')).toBe(4);
    const st = new Station('s');
    const r = createRobotFromLibrary('KUKA_KR6_R900');
    const base = new Frame('KUKA KR 6 Base 10');
    st.addChild(base);
    base.addChild(r);
    const p = new Program('P');
    st.addChild(p);
    p.setRobot(r);
    p.setFrame(base);
    p.addMoveJ([0, -90, 90, 0, 30, 0]);
    expect((compileForPost(st, p).events[0] as any).frameId).toBe(0);
  });
});

describe('zero-length linear moves (RoboDK "Skipped move")', () => {
  const robot = createRobotFromLibrary('UR10e');
  const prog = (events: PostEvent[]): PostProgram => ({ name: 'P', robot, robotName: robot.name, dof: 6, jointNames: [], events, subprograms: [], frame: { pose: identity(), name: 'W' }, tool: { pose: identity(), name: 'T' }, problems: [] });
  const at = (x: number, a = 0): Mat4 => multiply(transl(x, 0, 300), rotz(a));
  it('drops a MoveL to the point and orientation of the previous move, keeps a MoveL that only turns, keeps MoveJ', () => {
    const p = prog([
      { kind: 'moveL', joints: null, pose: at(100), name: 'first' },        // first move of the run: kept
      { kind: 'moveL', joints: null, pose: at(100), name: 'same' },         // dropped (10.a Weld1 MoveL 4)
      { kind: 'moveL', joints: null, pose: at(100, 0.5), name: 'turn' },    // kept (08.a Prog1 C -90 -> -40)
      { kind: 'moveJ', joints: [1, 2, 3, 4, 5, 6], pose: at(100, 0.5), name: 'j' }, // MoveJ kept
      { kind: 'moveL', joints: [1, 2, 3, 4, 5, 6], pose: at(500), name: 'samejoints' }, // same joints: dropped (05.c)
    ]);
    dropZeroLengthMoves([p], robot);
    expect(p.events.map((e: any) => e.name)).toEqual(['first', 'turn', 'j']);
    expect(p.skippedMoves).toBe(2);
  });

  it('end to end: a Library-like program posted through KUKA KRC2 loses the duplicate LIN', () => {
    const st = new Station('s');
    const r = createRobotFromLibrary('KUKA_KR6_R900');
    st.addChild(r);
    const f = new Frame('F');
    st.addChild(f);
    f.setPose(transl(500, 0, 300));
    const t = new Target('T');
    f.addChild(t);
    t.setPose(transl(0, 0, 0));
    const p = new Program('P');
    st.addChild(p);
    p.setRobot(r);
    p.setFrame(f);
    p.addMoveL(t);
    p.addMoveL(t);
    const src = getPost('KUKA_KRC2')!.generate(compileForPost(st, p))[0].content;
    expect(src.match(/^LIN /gm)?.length).toBe(1);
    void recordPostCalls;
  });
});
