describe('robomath Mat', () => {
  it('converts between pose representations and prints rows', () => {
    const m = robomath.transl(100, 200, 300).mul(robomath.rotz(90 * DEG));
    expect(m.Pos()).toEqual([100, 200, 300]);
    expect(m.rows().length).toBe(4);
    expect(m.toString().split('\n').length).toBe(4);
    expect(m.toArray().length).toBe(16);
    const back = m.mul(m.inv());
    expect(back.Pos()[0]).toBeCloseTo(0, 6);
    expect(back.rows()[0][0]).toBeCloseTo(1, 9);
    m.setPos([1, 2, 3]);
    expect(m.Pos()).toEqual([1, 2, 3]);
    const xyzrpw = m.Pose_2_TxyzRxyz();
    expect(xyzrpw.slice(0, 3)).toEqual([1, 2, 3]);
    expect(robomath.TxyzRxyz_2_Pose(xyzrpw).Pos()[2]).toBeCloseTo(3);
    const kuka = m.Pose_2_KUKA();
    expect(robomath.KUKA_2_Pose(kuka).rows()[0][0]).toBeCloseTo(m.rows()[0][0], 6);
    expect(robomath.Pose_2_KUKA(m)).toEqual(kuka);
    expect(robomath.Pose_2_TxyzRxyz(m)).toEqual(xyzrpw);
    const fanuc = m.Pose_2_Fanuc();
    expect(robomath.Fanuc_2_Pose(fanuc).Pos()[1]).toBeCloseTo(2);
    const ur = m.Pose_2_UR();
    expect(ur.length).toBe(6);
    expect(robomath.UR_2_Pose(ur).Pos()[0]).toBeCloseTo(1);
    expect(robomath.Pose_2_UR(m)).toEqual(ur);
    const abb = m.Pose_2_ABB();
    expect(abb.length).toBe(7);
    expect(robomath.ABB_2_Pose(abb).Pos()[2]).toBeCloseTo(3);
    expect(robomath.eye().rows()[3]).toEqual([0, 0, 0, 1]);
    expect(robomath.rotx(0).rows()[1][1]).toBe(1);
    expect(robomath.roty(0).rows()[2][2]).toBe(1);
    expect(RL.transl_(5, 6, 7).Pos()).toEqual([5, 6, 7]);
    expect(Mat.fromRows(m.rows()).toArray()).toEqual(m.toArray());
    expect(robomath.pi).toBe(Math.PI);
  });
});

