    expect(box.Color().slice(0, 3)).toEqual([1, 0, 0]);
    box.Recolor('#00ff00');
    expect(box.Color()[1]).toBe(1);
    box.setColorShape([0, 0, 1], 0);
    expect((box.item as SceneObject).geometry[0].color).toBe('#0000ff');
    box.setColorShape('#123456', 99);
    box.setColorCurve([0.5, 0.5, 0.5]);
    expect(box.getParam('curveColor')).toBe('#808080');
    box.setParam('sku', 'A1');
    expect(box.getParam('sku')).toBe('A1');
    // geometry pose
    box.setGeometryPose(robomath.transl(0, 0, 10));
    expect(box.GeometryPose().Pos()[2]).toBe(10);
    const plain = RDK.AddFrame('Plain');
    expect(plain.GeometryPose().Pos()).toEqual([0, 0, 0]);
    expect(plain.setGeometryPose(robomath.transl(1, 1, 1))).toBe(plain);
    // object links & scale with mesh geometry and curves
    expect(RDK.Item('Table', RL.ITEM_TYPE_FRAME).ObjectLink(0).Name()).toBe('Table top');
    expect(box.ObjectLink(5).Valid()).toBe(false);
    const meshObj = RDK.AddCurve([[0, 0, 0], [100, 0, 0]]);
    (meshObj.item as SceneObject).geometry = [{ mesh: 'm1', scale: [1, 1, 1] }, { primitive: { kind: 'sphere', radius: 10 } }, { primitive: { kind: 'cylinder', radius: 5, length: 20 } }];
    meshObj.Scale([2, 3]);
    const g = (meshObj.item as SceneObject).geometry;
    expect(g[0].scale).toEqual([2, 3, 2]);
    expect((g[1].primitive as any).radius).toBe(20);
    expect((g[2].primitive as any).length).toBe(40);
    expect((meshObj.item as SceneObject).curves[0].points[1][0]).toBe(200);
    // attach / detach closest
    robot.MoveJ(RDK.Item('Pick 1'));
    const attached = robot.AttachClosest();
    expect(attached.Name()).toBe('Box 1');
    expect(RDK.events.drain().some((e) => e.type === 'attach')).toBe(true);
    const detached = robot.DetachClosest();
    expect(detached.item).toBe(attached.item);
    expect(detached.Parent().Type()).toBe(RL.ITEM_TYPE_STATION);
    expect(robot.DetachClosest().Valid()).toBe(false);
    const tool = robot.getLink(RL.ITEM_TYPE_TOOL);
    expect(tool.AttachClosest(1).Valid()).toBe(false);
    const again = tool.AttachClosest();
    expect(again.Valid()).toBe(true);
    expect((tool.item as Tool).attached).toContain(again.item!.id);
    const holder = RDK.AddFrame('Holder');
    tool.DetachClosest(holder);
    expect(again.Parent().item).toBe(holder.item);
    expect((tool.item as Tool).attached).toEqual([]);
    tool.AttachClosest();
    robot.MoveJ(RDK.Item('Above 2'));
    expect(tool.AttachClosest().Name()).toBe('Box 2');
    expect(tool.Childs().length).toBe(2);
    expect(tool.DetachClosest().Name()).toBe('Box 1'); // the nearer of the two attached objects (Box 2 hangs 300 mm below)
    expect(tool.Childs().map((c) => c.Name())).toEqual(['Box 2']);
    tool.DetachAll(holder);
    expect(tool.Childs().length).toBe(0);
    // collisions
    expect(box.Collision(new RobolinkItem(RDK, null))).toBe(0);
    expect(box.Collision(table)).toBeGreaterThanOrEqual(0);
    const b2 = RDK.Item('Box 2', RL.ITEM_TYPE_OBJECT);
    b2.setPoseAbs(box.PoseAbs());
    expect(box.Collision(b2)).toBe(1);
    // copy / paste at item level
    box.Copy();
    const pasted = box.Parent().Paste();
    expect(pasted.Valid()).toBe(true);
    expect(pasted.Name()).not.toBe('Box 1');
    // MoveL_Test and SearchL
    robot.MoveJ(RDK.Item('Home'));
    const q0 = robot.Joints();
    const pose = robot.Pose();
    expect(robot.MoveL_Test(q0, pose.mul(robomath.transl(0, 0, -20)))).toBe(0);
