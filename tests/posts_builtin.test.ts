/**
 * RoboDK's BUILT-IN generators (src/posts/rdk_builtin.ts): what RoboDK 5.9.4 writes for a robot whose station stores
 * no post processor, and the "undefined post processor" placeholder of mechanisms.
 *
 * Ground truth: tests/fixtures/posts_gt/builtin/<brand>/ written by RoboDK itself (make_builtin_gt.py): feature programs
 * (every instruction kind) added through RoboDK's API to Library stations whose robot has no post (06.b ABB, 08.a
 * KUKA, 06.d Fanuc + gripper, 07.e UR, 05.d Comau on its gantry) and generated with MakeProgram. The test opens the
 * same Library station in the studio, adds the same frames / tools / targets (RoboDK's own poses and joints from
 * station.json) and programs through the studio's Robolink API, and compares every file RoboDK wrote line by line
 * (tests/posts_library_util.ts diffTolerant: case-insensitive, numbers within 0.011, date / "generated by" lines
 * ignored).
 */
import { describe, it, expect } from 'vitest';
import { existsSync, readdirSync, readFileSync } from 'node:fs';
import path from 'node:path';
import { loadLibraryStation, LIB, diffTolerant, rdkHeader } from './posts_library_util';
import { Robolink, RobolinkItem, ITEM_TYPE_ROBOT, ITEM_TYPE_FRAME, ITEM_TYPE_TOOL, ITEM_TYPE_PROGRAM, INSTRUCTION_COMMENT, INSTRUCTION_SHOW_MESSAGE, INSTRUCTION_CALL_PROGRAM, INSTRUCTION_INSERT_CODE, INSTRUCTION_START_THREAD, Mat } from '../src/api/robolink';
import { compileForPost, getPost } from '../src/posts/index';
import { Robot } from '../src/core/items/robot';
import { Program } from '../src/core/items/program';
import { fromArray, multiply, rotz, transl } from '../src/core/math/pose';

const DIR = path.resolve(__dirname, 'fixtures/posts_gt/builtin');
interface Info {
  brand: string; station: string; robot: string; dof: number; joints: number[]; skipped?: string[];
  frames?: Record<string, { pose: number[]; parent: string }>; tools?: Record<string, number[]>;
  targets?: Record<string, { pose: number[]; joints: number[]; isJoint: boolean; frame: string }>;
  programs: Record<string, { files: string[] }>;
}
const brands = existsSync(DIR) ? readdirSync(DIR).filter((d) => existsSync(path.join(DIR, d, 'station.json'))) : [];
/** RoboDK row-major 16 numbers -> Mat of the studio API. */
const M = (v: number[]) => new Mat(fromArray([0, 1, 2, 3].flatMap((c) => [0, 1, 2, 3].map((r) => v[r * 4 + c]))));
const safe = (s: string) => s.replace(/[^A-Za-z0-9_-]/g, '_');

/** The feature programs of make_builtin_gt.py, step for step, through the studio's Robolink API. */
function buildFeature(rdk: Robolink, robot: RobolinkItem, info: Info): RobolinkItem[] {
  robot.setJoints(info.joints);
  if (info.brand === 'Mechanism') {
    const prog = rdk.AddProgram('MechProg', robot);
    const parent = new RobolinkItem(rdk, robot.item!.parent);
    const t1 = rdk.AddTarget('Mech Open', parent, robot); t1.setAsJointTarget(); t1.setJoints(Array(info.dof).fill(0));
    const t2 = rdk.AddTarget('Mech Close', parent, robot); t2.setAsJointTarget(); t2.setJoints([12.5, ...Array(info.dof - 1).fill(0)]);
    prog.MoveJ(t1); prog.Pause(500); prog.RunInstruction('Mech comment', INSTRUCTION_COMMENT); prog.setDO('7', 1); prog.MoveJ(t2);
    return [prog];
  }
  const fr = (name: string) => {
    const f = info.frames![name];
    const existing = rdk.Item(name, ITEM_TYPE_FRAME);
    if (existing.Valid()) return existing;
    const it = rdk.AddFrame(name);
    it.setPose(M(f.pose));
    return it;
  };
  const frameNames = Object.keys(info.frames!), toolNames = Object.keys(info.tools!);
  const frame = fr(frameNames[0]), frame2 = fr(frameNames[1]);
  const tl = (name: string) => { const ex = rdk.Item(name, ITEM_TYPE_TOOL); return ex.Valid() ? ex : robot.AddTool(M(info.tools![name]), name); };
  const tool = tl(toolNames[0]), tool2 = tl(toolNames[1]);
  robot.setPoseTool(tool);
  robot.setPoseFrame(frame);
  const T: Record<string, RobolinkItem> = {};
  for (const [name, t] of Object.entries(info.targets!)) {
    const it = rdk.AddTarget(name, t.frame === frameNames[0] ? frame : frame2, robot);
    if (t.isJoint) it.setAsJointTarget(); else it.setAsCartesianTarget();
    it.setPose(M(t.pose));
    it.setJoints(t.joints);
    T[name] = it;
  }
  robot.setJoints(info.joints);
  const sub = rdk.AddProgram('SubProg', robot);
  sub.setPoseFrame(frame); sub.setPoseTool(tool); sub.MoveL(T['Target 1']); sub.RunInstruction('Inside sub', INSTRUCTION_COMMENT);
  const thr = rdk.AddProgram('ThreadProg', robot); thr.RunInstruction('Thread body', INSTRUCTION_COMMENT);
  const spaced = rdk.AddProgram('Spaced Name', robot); spaced.RunInstruction('Spaced body', INSTRUCTION_COMMENT);
  const longp = rdk.AddProgram('Long_Program Name12', robot); longp.RunInstruction('Long body', INSTRUCTION_COMMENT); longp.setPoseTool(tool2); longp.MoveL(T['Target 3']);
  const prog = rdk.AddProgram('Feature', robot);
  const t1 = T['Target 1'], t5 = T['Target 5'];
  const rel = (t: RobolinkItem, m: Float64Array) => new Mat(multiply(t.Pose().m, m));
  const steps: Array<[string, () => void]> = [
    ['frame', () => prog.setPoseFrame(frame)], ['tool', () => prog.setPoseTool(tool)], ['movej_joint', () => prog.MoveJ(T['Start Joints'])],
    ['speed', () => prog.setSpeed(250)], ['rounding', () => prog.setRounding(5)], ['movej_cart', () => prog.MoveJ(t1)], ['movel_cart', () => prog.MoveL(T['Target 2'])],
    ['movel_joint', () => prog.MoveL(T['Joint Line'])], ['movec', () => prog.MoveC(T['Target 3'], T['Target 4'])], ['fine', () => prog.setRounding(-1)],
    ['speed_joints', () => prog.setSpeed(-1, 45)], ['speed_accel', () => prog.setSpeed(120, -1, 800)], ['movel_back', () => prog.MoveL(t1)], ['movel_same', () => prog.MoveL(t1)],
    ['movel_rot', () => prog.MoveL(rel(t1, rotz(Math.PI / 9)))], ['movej_same', () => prog.MoveJ(t1)],
    ['speed_all', () => { prog.setSpeed(300, 60, 1500, 200); prog.setSpeed(-1, -1, -1, 150); prog.setSpeed(-1, -1, 50); }],
    ['do', () => { prog.setDO('5', 1); prog.setDO('3', 0); }], ['wait', () => prog.waitDI('2', 1)], ['wait_timeout', () => prog.waitDI('4', 0, 2500)],
    ['pause', () => prog.Pause(1500)], ['stop', () => prog.Pause()], ['comment', () => prog.RunInstruction('A comment line', INSTRUCTION_COMMENT)],
    ['message', () => prog.RunInstruction('A message', INSTRUCTION_SHOW_MESSAGE)],
    ['call', () => { prog.RunInstruction('SubProg', INSTRUCTION_CALL_PROGRAM); prog.RunInstruction('Spaced Name', INSTRUCTION_CALL_PROGRAM); }],
    ['call_external', () => prog.RunInstruction('ExternalProg', INSTRUCTION_CALL_PROGRAM)],
    ['call_more', () => { for (const c of ['Long_Program Name12', 'Another Long_External Name', 'SetRPM(700)', 'Ab_c']) prog.RunInstruction(c, INSTRUCTION_CALL_PROGRAM); }],
    ['code', () => prog.RunInstruction('custom_code(1)', INSTRUCTION_INSERT_CODE)], ['thread', () => prog.RunInstruction('ThreadProg', INSTRUCTION_START_THREAD)],
    ['ao', () => prog.setAO('2', 3.5)], ['frame2', () => { prog.setPoseFrame(frame2); prog.setPoseTool(tool2); }], ['movej_t5', () => prog.MoveJ(t5)],
    ['movej_inline', () => prog.MoveJ(info.joints)], ['movel_inline', () => prog.MoveL(rel(t5, transl(0, 0, -20)))],
    ['back', () => { prog.setPoseTool(tool); prog.setPoseFrame(frame); prog.MoveJ(T['Start Joints']); }],
  ];
  for (const [key, fn] of steps) if (!(info.skipped ?? []).includes(key)) fn();
  // RoboDK stores joints with an inline target added through its API (IK from the robot's state at insertion, in the
  // robot's active frame); its generators then write those joints as stored: the inline moves get RoboDK's joints
  const rdkInline = (info.programs.Feature as any).instructions.filter((i: any) => i.type === 0 && /^Move[JLC] \d+$/.test(i.name));
  const mine = (prog.item as Program).instructions().filter((i) => i.data.kind === 'move' && !i.data.targetId);
  mine.forEach((ins, k) => { const j = rdkInline[k]?.joints; if (j && ins.data.kind === 'move') ins.data.joints = j.slice(); });
  robot.setPoseTool(tool);
  robot.setPoseFrame(frame);
  return [sub, spaced, thr, longp, prog];
}

describe('RoboDK built-in generators (robots without a post processor) equal RoboDK 5.9.4', () => {
  for (const b of brands) {
    const info: Info = JSON.parse(readFileSync(path.join(DIR, b, 'station.json'), 'utf8'));
    it.skipIf(!existsSync(path.join(LIB, info.station)))(`${b}: ${info.robot} in ${info.station}`, async () => {
      const st = await loadLibraryStation(info.station);
      const rdk = new Robolink(st);
      const robot = rdk.Item(info.robot, ITEM_TYPE_ROBOT);
      const r = robot.item as Robot;
      expect(r.params.rdkPostProcessor, 'the station stores no post').toBe('');
      expect(r.postProcessor).toMatch(/^RoboDK_Builtin_/);
      const progs = buildFeature(rdk, robot, info);
      const bad: string[] = [];
      for (const p of progs) {
        const prog = p.item as Program;
        const gt = info.programs[prog.name];
        if (!gt) continue;
        const files = getPost(r.postProcessor)!.generate(compileForPost(st, prog), { headerComments: rdkHeader(r.name) });
        for (const f of gt.files) {
          const mine = files.find((x) => x.name.toLowerCase() === f.toLowerCase());
          if (!mine) { bad.push(`${prog.name}/${f}: studio wrote ${files.map((x) => x.name).join(',')}`); continue; }
          const d = diffTolerant(readFileSync(path.join(DIR, b, safe(prog.name), f), 'latin1'), mine.content);
          if (d) bad.push(`${prog.name}/${f}: ${d}`);
        }
      }
      expect(bad).toEqual([]);
      void ITEM_TYPE_PROGRAM;
    }, 120000);
  }
});
