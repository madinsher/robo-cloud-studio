const afterKey = (s: string, p: string, f: string) => `${s}|${p.replace(/[^\p{L}\p{N}]/gu, '').toLowerCase()}|${f.toLowerCase()}`;
const AFTER = new Map(AFTER_DIFF.map(([s, p, f, r]) => [afterKey(s, p, f), r]));

describe('A) station -> code equals RoboDK MakeProgram from the station as loaded (events, posts, end to end)', () => {
  it("has RoboDK's as-loaded code of the Library stations", () => { expect(existsSync(LOADED_TGZ)).toBe(true); });
  for (const file of STATIONS) {
    it.skipIf(!existsSync(LIB))(file, async () => {
      const rows = await compareLoaded(file);
      const bad: string[] = [];
      for (const r of rows) {
        if (r.e2e.startsWith('RoboDK: ')) continue;   // RoboDK did not return from MakeProgram (post blocked)
        const k = `${file}|${r.program}|${r.file}`;
        const ok = r.e2e === 'equal' && (r.events === 'equal' || r.events === '-') && (r.post === 'equal' || r.post === '-');
        if (ok && LOADED_DIFF[k]) bad.push(`${k}: now equal, update LOADED_DIFF and docs/posts.md`);
        if (!ok && !LOADED_DIFF[k]) bad.push(`${k}: events ${r.events} | post ${r.post} | e2e ${r.e2e}`);
      }
      expect(bad).toEqual([]);
    }, 600000);
  }
});

describe('B) station -> code equals RoboDK MakeProgram after Item.Update (robodk_generated_code.tgz)', () => {
  for (const file of STATIONS) {
    it.skipIf(!haveLibrary(file))(file, async () => {
      const rows = await compareStationCode(file, undefined, 0.011, {}, 'simulated');
      const bad: string[] = [];
      for (const r of rows) {
        const why = AFTER.get(afterKey(file, r.program, r.file));
        if (r.status === 'equal' && why) bad.push(`${r.program}/${r.file}: now equal, update AFTER_DIFF and docs/posts.md`);
        if (r.status !== 'equal' && !why) bad.push(`${r.program}/${r.file}: ${r.status} ${r.detail ?? ''}`);
      }
      expect(bad).toEqual([]);
    }, 600000);
  }
});

describe('programs of other robots and mechanisms are called, never posted as moves of the caller', () => {
  const B = 'Example-05.b-Glazing with a turntable - ABB.rdk';
  it.skipIf(!haveLibrary(B))('05.b Inside1 (IRB 2600) only calls TT0deg, the 1-axis turntable program', async () => {
    const st = await loadLibraryStation(B);
    const p = st.itemsOfType<Program>(ItemType.PROGRAM).find((x) => x.name === 'Inside1')!;
    const tt = st.itemsOfType<Program>(ItemType.PROGRAM).find((x) => x.name === 'TT0deg')!;
    expect(tt.robot()).not.toBe(p.robot());
    const compiled = compileForPost(st, p);
    expect(compiled.subprograms.map((s) => s.name)).not.toContain('TT0deg');
    const mod = getPost((p.robot() as Robot).postProcessor)!.generate(compiled).map((f) => f.content).join('\n');
    expect(mod).not.toMatch(/PROC TT0deg/);
    expect(mod).toMatch(/^\s*TT0deg;\s*$/m);
    // the arm never drives to the turntable's all-zero joint vector
    expect(mod).not.toMatch(/MoveAbsJ \[\[0\.000000,0\.000000,0\.000000,0\.000000,0\.000000,0\.000000\]/);
  }, 120000);
  const F = 'Example-06.f-Pick and Place CNC and Dual RobotiQ Gripper-UR10.rdk';
  it.skipIf(!haveLibrary(F))('06.f Drop 1 (UR10e) calls OpenGripper2 of the RobotiQ gripper without defining it as UR moves', async () => {
    const st = await loadLibraryStation(F);
    const p = st.itemsOfType<Program>(ItemType.PROGRAM).find((x) => x.name === 'Drop 1')!;
    const script = getPost((p.robot() as Robot).postProcessor)!.generate(compileForPost(st, p)).find((f) => f.name.endsWith('.script'))!.content;
    expect(script).not.toMatch(/def OpenGripper2\(\)/);
    expect(script).toMatch(/^\s*OpenGripper2\(\)\s*$/m);
    expect(script).not.toMatch(/movej\(\[0\.872665, 0\.000000, 0\.000000/);
  }, 120000);
});
